// Generates src/http/routes.generated.ts from ../contract/openapi.yaml (the route inventory the server registers).
// Usage: node scripts/gen-routes.ts [--check]   (--check exits 1 when the committed file is stale)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
export const OUT = join(here, "..", "src", "http", "routes.generated.ts");
const METHODS = ["get", "post", "put", "delete", "patch"] as const;

export function generate(openapiYaml: string): string {
  const doc = parse(openapiYaml);
  const rows: string[] = [];
  for (const [path, item] of Object.entries<any>(doc.paths)) {
    for (const m of METHODS) {
      const op = item[m];
      if (!op) continue;
      const auth = op["x-vlad-auth"];
      if (!["none", "session", "session+approval"].includes(auth)) throw new Error(`${op.operationId}: x-vlad-auth eksik/geçersiz`);
      const fastifyPath = `/v1${path.replace(/\{([^}]+)\}/g, ":$1")}`;
      rows.push(`  { operationId: ${JSON.stringify(op.operationId)}, method: ${JSON.stringify(m.toUpperCase())}, path: ${JSON.stringify(fastifyPath)}, auth: ${JSON.stringify(auth)} },`);
    }
  }
  return `// GENERATED by scripts/gen-routes.ts from contract/openapi.yaml. Do not edit; run \`npm run gen:routes\`.
export type AuthKind = "none" | "session" | "session+approval";
export type RouteSpec = { operationId: string; method: string; path: string; auth: AuthKind };

export const ROUTES: readonly RouteSpec[] = [
${rows.join("\n")}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = generate(readFileSync(join(here, "..", "..", "contract", "openapi.yaml"), "utf8"));
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf8") !== next) {
      console.error("routes.generated.ts eski: npm run gen:routes");
      process.exit(1);
    }
  } else writeFileSync(OUT, next);
}
